def _downsample_for_plot(
	features: np.ndarray,
	scores: np.ndarray,
	max_points: int,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
	"""Downsample epochs for plotting to keep figures responsive."""
	n = len(scores)
	if n == 0:
		return np.array([], dtype=int), features, scores

	if max_points <= 0 or n <= max_points:
		x = np.arange(n)
		return x, features, scores

	stride = int(np.ceil(n / max_points))
	indices = np.arange(0, n, stride)
	return indices, features[indices], scores[indices]


def _downsample_stage_values(stage_values: np.ndarray, max_points: int) -> tuple[np.ndarray, np.ndarray]:
	"""Downsample a stage trace while preserving transitions for plotting."""
	n = len(stage_values)
	if n == 0:
		return np.array([], dtype=int), np.array([], dtype=int)

	if max_points <= 0 or n <= max_points:
		return np.arange(n), stage_values

	stride = int(np.ceil(n / max_points))
	indices = np.arange(0, n, stride)
	return indices, stage_values[indices]


def _find_feature_index(feature_names: Sequence[str], target: str) -> int:
	"""Find feature index by normalized name; returns -1 if not found."""
	norm_target = target.lower().replace(" ", "").replace("-", "").replace("_", "")
	for i, name in enumerate(feature_names):
		norm_name = str(name).lower().replace(" ", "").replace("-", "").replace("_", "")
		if norm_name == norm_target:
			return i
	return -1


def _find_first_feature_index(feature_names: Sequence[str], candidates: Sequence[str]) -> int:
	"""Return first matching feature index from candidate names, else -1."""
	for candidate in candidates:
		idx = _find_feature_index(feature_names, candidate)
		if idx >= 0:
			return idx
	return -1


def derive_stage_trace_from_features(
	features: np.ndarray,
	feature_names: Sequence[str],
	fallback_scores: np.ndarray,
) -> np.ndarray:
	"""
	Build stage transitions from feature indices.

	Rules:
	- Wake = Index_W
	- NREM = Index_N, then subtype via max(Index_1, Index_2, Index_3) -> N1/N2/N3
	- REM = Index_R
	"""
	idx_w = _find_first_feature_index(feature_names, ["Index_W"])
	idx_n = _find_first_feature_index(feature_names, ["Index_N", "Index_N_EOG", "Index_N_noEOG"])
	idx_r = _find_first_feature_index(feature_names, ["Index_R", "Index_R_EOG", "Index_R_noEOG"])
	idx_1 = _find_feature_index(feature_names, "Index_1")
	idx_2 = _find_feature_index(feature_names, "Index_2")
	idx_3 = _find_feature_index(feature_names, "Index_3")

	required = [idx_w, idx_n, idx_r, idx_1, idx_2, idx_3]
	if any(i < 0 for i in required):
		return fallback_scores

	n = features.shape[0]
	derived = np.zeros(n, dtype=int)

	broad = np.column_stack(
		[
			np.nan_to_num(features[:, idx_w], nan=-np.inf),
			np.nan_to_num(features[:, idx_n], nan=-np.inf),
			np.nan_to_num(features[:, idx_r], nan=-np.inf),
		]
	)
	broad_choice = np.argmax(broad, axis=1)

	# 0 -> Wake, 1 -> NREM, 2 -> REM
	derived[broad_choice == 0] = 0
	derived[broad_choice == 2] = 4

	nrem_mask = broad_choice == 1
	if np.any(nrem_mask):
		nrem_sub = np.column_stack(
			[
				np.nan_to_num(features[nrem_mask, idx_1], nan=-np.inf),
				np.nan_to_num(features[nrem_mask, idx_2], nan=-np.inf),
				np.nan_to_num(features[nrem_mask, idx_3], nan=-np.inf),
			]
		)
		sub_choice = np.argmax(nrem_sub, axis=1)
		# 0->N1 (1), 1->N2 (2), 2->N3 (3)
		derived[nrem_mask] = sub_choice + 1

	return derived



def _most_common_stage_per_epoch(stage_sequences: List[np.ndarray]) -> np.ndarray:
	"""Compute consensus stage by epoch index across subjects."""
	if not stage_sequences:
		return np.array([], dtype=int)

	max_len = max(len(seq) for seq in stage_sequences)
	consensus = np.zeros(max_len, dtype=int)

	for epoch_idx in range(max_len):
		values = [int(seq[epoch_idx]) for seq in stage_sequences if epoch_idx < len(seq)]
		if not values:
			consensus[epoch_idx] = 0
			continue

		arr = np.asarray(values, dtype=int)
		arr = arr[arr >= 0]
		if arr.size == 0:
			consensus[epoch_idx] = 0
			continue

		counts = np.bincount(arr)
		consensus[epoch_idx] = int(np.argmax(counts))

	return consensus


def plot_subject_and_consensus_hypnograms(
	subject_data: List[SubjectData],
	feature_names: Sequence[str],
	output_dir: str,
	use_feature_derived: bool = False,
) -> None:
	"""Save one hypnogram per subject and one epoch-wise consensus hypnogram.

	By default this uses true scored labels from HDF5. Set
	`use_feature_derived=True` to use feature-derived stage transitions.
	"""
	if use_feature_derived:
		subject_dir = os.path.join(output_dir, "subject_hypnograms_feature_derived")
		consensus_png = "hypnogram_consensus_feature_derived_most_common_stage_per_epoch.png"
		consensus_csv = "hypnogram_consensus_feature_derived_per_epoch.csv"
		title_suffix = "feature-derived stage transitions"
	else:
		subject_dir = os.path.join(output_dir, "subject_hypnograms")
		consensus_png = "hypnogram_consensus_most_common_stage_per_epoch.png"
		consensus_csv = "hypnogram_consensus_per_epoch.csv"
		title_suffix = "true scored stages"
	os.makedirs(subject_dir, exist_ok=True)

	stage_sequences: List[np.ndarray] = []
	consensus_rows: List[Dict[str, float]] = []

	for subj in subject_data:
		if use_feature_derived:
			stage_values = derive_stage_trace_from_features(subj.features, feature_names, subj.scores)
		else:
			stage_values = np.asarray(subj.scores, dtype=int)

		stage_sequences.append(stage_values)
		plot_stage_hypnogram(
			stage_values=stage_values,
			out_path=os.path.join(subject_dir, f"hypnogram_{_sanitize_name(subj.subject)}.png"),
			title=f"Hypnogram ({subj.subject}) - {title_suffix}",
		)

	consensus = _most_common_stage_per_epoch(stage_sequences)
	plot_stage_hypnogram(
		stage_values=consensus,
		out_path=os.path.join(output_dir, consensus_png),
		title="Consensus Hypnogram - most common stage per epoch index",
	)

	for epoch_idx, stage in enumerate(consensus):
		n_subjects = int(sum(1 for seq in stage_sequences if epoch_idx < len(seq)))
		consensus_rows.append(
			{
				"epoch": epoch_idx,
				"consensus_stage": int(stage),
				"consensus_stage_name": STAGE_NAMES.get(int(stage), f"Stage_{int(stage)}"),
				"n_subjects_contributing": n_subjects,
			}
		)

	_write_csv(
		path=os.path.join(output_dir, consensus_csv),
		rows=consensus_rows,
		columns=["epoch", "consensus_stage", "consensus_stage_name", "n_subjects_contributing"],
	)



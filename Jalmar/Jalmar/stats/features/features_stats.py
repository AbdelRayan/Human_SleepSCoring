def build_parser() -> argparse.ArgumentParser:
	parser = argparse.ArgumentParser(
		description="Compute feature statistics/plots from Jalmar sleep HDF5 for mcRBM feature selection."
	)
	parser.add_argument("--hdf5", required=True, help="Path to HDF5 file with subject groups/features/scores.")
	parser.add_argument(
		"--output_dir",
		default="feature_stats_output",
		help="Directory where CSV files and plots will be saved.",
	)
	parser.add_argument(
		"--include_artifacts",
		action="store_true",
		help="Include stage 5 (Movement/Artifact) epochs in analysis.",
	)
	return parser


def main() -> None:
	parser = build_parser()
	args = parser.parse_args()
	run_analysis(
		hdf5_path=args.hdf5,
		output_dir=args.output_dir,
		include_artifacts=args.include_artifacts,
	)


if __name__ == "__main__":
	main()

def _safe_correlation_matrix(features: np.ndarray) -> np.ndarray:
	x = np.asarray(features, dtype=float)
	with warnings.catch_warnings():
		warnings.simplefilter("ignore", RuntimeWarning)
		corr = np.corrcoef(x, rowvar=False)

	if corr.ndim == 0:
		corr = np.array([[1.0]])

	# Constant features create undefined correlations (NaN); set those to 0 off-diagonal.
	corr = np.where(np.isfinite(corr), corr, 0.0)
	n = corr.shape[0]
	for i in range(n):
		corr[i, i] = 1.0
	return corr



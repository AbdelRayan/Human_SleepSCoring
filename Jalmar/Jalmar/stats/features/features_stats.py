"""
Feature statistics and visualization pipeline for mcRBM feature selection.

This script reads an HDF5 file generated by the Jalmar hdf5 module, computes
statistics that reflect how informative each feature is for sleep-stage
separation, and exports plots/tables for feature set decisions.
"""

from __future__ import annotations

import argparse
import csv
import os
import warnings
from dataclasses import dataclass
from typing import Dict, List, Sequence

import h5py
import matplotlib.pyplot as plt
import numpy as np
from scipy.stats import f_oneway, kruskal, kurtosis, skew
from sklearn.decomposition import PCA
from sklearn.feature_selection import mutual_info_classif
from sklearn.preprocessing import StandardScaler


NEAR_CONSTANT_STD = 1e-12


STAGE_NAMES = {
	0: "Awake",
	1: "N1",
	2: "N2",
	3: "N3",
	4: "REM",
	5: "Movement/Artifact",
	6: "Unknown/Uncertain",
}


@dataclass
class LoadedData:
	features: np.ndarray
	scores: np.ndarray
	feature_names: List[str]
	subjects: np.ndarray


@dataclass
class SubjectData:
	subject: str
	features: np.ndarray
	scores: np.ndarray


def _parse_feature_names(description_attr: object, n_features: int) -> List[str]:
	if description_attr is None:
		return [f"Feature_{i + 1}" for i in range(n_features)]

	if isinstance(description_attr, bytes):
		description_attr = description_attr.decode("utf-8", errors="ignore")

	names = [part.strip() for part in str(description_attr).split(",") if part.strip()]
	if len(names) != n_features:
		return [f"Feature_{i + 1}" for i in range(n_features)]
	return names


def load_hdf5_features(hdf5_path: str, include_artifacts: bool = False) -> LoadedData:
	features_all: List[np.ndarray] = []
	scores_all: List[np.ndarray] = []
	subjects_all: List[np.ndarray] = []
	feature_names: List[str] | None = None

	with h5py.File(hdf5_path, "r") as h5f:
		for subject in h5f.keys():
			group = h5f[subject]
			if "features" not in group or "scores" not in group:
				continue

			features = np.asarray(group["features"][:], dtype=np.float64)
			scores = np.asarray(group["scores"][:], dtype=np.int32)

			min_len = min(len(features), len(scores))
			features = features[:min_len]
			scores = scores[:min_len]

			if not include_artifacts:
				mask = scores != 5
				features = features[mask]
				scores = scores[mask]

			if features.size == 0:
				continue

			if feature_names is None:
				description = group.attrs.get("description_features")
				feature_names = _parse_feature_names(description, features.shape[1])

			features_all.append(features)
			scores_all.append(scores)
			subjects_all.append(np.full(shape=len(scores), fill_value=subject, dtype=object))

	if not features_all:
		raise ValueError("No valid feature/scores data found in the HDF5 file.")

	return LoadedData(
		features=np.vstack(features_all),
		scores=np.concatenate(scores_all),
		feature_names=feature_names or [f"Feature_{i + 1}" for i in range(features_all[0].shape[1])],
		subjects=np.concatenate(subjects_all),
	)


def load_hdf5_subject_data(
	hdf5_path: str,
	include_artifacts: bool = False,
) -> tuple[List[SubjectData], List[str]]:
	"""Load per-subject feature and score sequences from HDF5."""
	subject_rows: List[SubjectData] = []
	feature_names: List[str] | None = None

	with h5py.File(hdf5_path, "r") as h5f:
		for subject in h5f.keys():
			group = h5f[subject]
			if "features" not in group or "scores" not in group:
				continue

			features = np.asarray(group["features"][:], dtype=np.float64)
			scores = np.asarray(group["scores"][:], dtype=np.int32)

			min_len = min(len(features), len(scores))
			features = features[:min_len]
			scores = scores[:min_len]

			if not include_artifacts:
				mask = scores != 5
				features = features[mask]
				scores = scores[mask]

			if features.size == 0:
				continue

			if feature_names is None:
				description = group.attrs.get("description_features")
				feature_names = _parse_feature_names(description, features.shape[1])

			subject_rows.append(SubjectData(subject=str(subject), features=features, scores=scores))

	if not subject_rows:
		raise ValueError("No per-subject data found in HDF5.")

	if feature_names is None:
		feature_names = [f"Feature_{i + 1}" for i in range(subject_rows[0].features.shape[1])]

	return subject_rows, feature_names


def _safe_stats(x: np.ndarray) -> Dict[str, float]:
	valid = x[np.isfinite(x)]
	if valid.size == 0:
		return {
			"n": 0,
			"mean": np.nan,
			"std": np.nan,
			"median": np.nan,
			"q25": np.nan,
			"q75": np.nan,
			"iqr": np.nan,
			"min": np.nan,
			"max": np.nan,
			"skew": np.nan,
			"kurtosis": np.nan,
			"outlier_pct": np.nan,
		}

	q25, q75 = np.percentile(valid, [25, 75])
	iqr = q75 - q25
	lo = q25 - 1.5 * iqr
	hi = q75 + 1.5 * iqr
	outlier_pct = float(np.mean((valid < lo) | (valid > hi)) * 100.0)
	std_val = float(np.std(valid, ddof=1)) if valid.size > 1 else 0.0
	is_constant = bool(np.nanmax(valid) - np.nanmin(valid) <= NEAR_CONSTANT_STD)

	if is_constant:
		skew_val = np.nan
		kurtosis_val = np.nan
	else:
		with warnings.catch_warnings():
			warnings.simplefilter("ignore", RuntimeWarning)
			skew_val = float(skew(valid, bias=False)) if valid.size > 2 else np.nan
			kurtosis_val = float(kurtosis(valid, bias=False)) if valid.size > 3 else np.nan

	return {
		"n": float(valid.size),
		"mean": float(np.mean(valid)),
		"std": std_val,
		"median": float(np.median(valid)),
		"q25": float(q25),
		"q75": float(q75),
		"iqr": float(iqr),
		"min": float(np.min(valid)),
		"max": float(np.max(valid)),
		"skew": skew_val,
		"kurtosis": kurtosis_val,
		"is_constant": int(is_constant),
		"outlier_pct": outlier_pct,
	}


def feature_basic_statistics(features: np.ndarray, feature_names: Sequence[str]) -> List[Dict[str, float]]:
	rows: List[Dict[str, float]] = []
	for idx, fname in enumerate(feature_names):
		stats_row = _safe_stats(features[:, idx])
		stats_row["feature"] = fname
		rows.append(stats_row)
	return rows


def feature_stage_statistics(
	features: np.ndarray,
	scores: np.ndarray,
	feature_names: Sequence[str],
) -> List[Dict[str, float]]:
	rows: List[Dict[str, float]] = []
	unique_stages = sorted(int(s) for s in np.unique(scores))

	for idx, fname in enumerate(feature_names):
		x = features[:, idx]
		for stage in unique_stages:
			stage_values = x[scores == stage]
			stage_stats = _safe_stats(stage_values)
			stage_stats["feature"] = fname
			stage_stats["stage"] = stage
			stage_stats["stage_name"] = STAGE_NAMES.get(stage, f"Stage_{stage}")
			rows.append(stage_stats)

	return rows


def _fisher_score_per_feature(x: np.ndarray, y: np.ndarray, classes: np.ndarray) -> float:
	global_mean = np.mean(x)
	numerator = 0.0
	denominator = 0.0

	for c in classes:
		xc = x[y == c]
		if xc.size == 0:
			continue
		mu_c = np.mean(xc)
		var_c = np.var(xc, ddof=1) if xc.size > 1 else 0.0
		numerator += xc.size * (mu_c - global_mean) ** 2
		denominator += xc.size * var_c

	return float(numerator / (denominator + 1e-12))


def _eta_squared(x: np.ndarray, y: np.ndarray, classes: np.ndarray) -> float:
	grand_mean = np.mean(x)
	ss_total = np.sum((x - grand_mean) ** 2)
	ss_between = 0.0

	for c in classes:
		xc = x[y == c]
		if xc.size == 0:
			continue
		ss_between += xc.size * (np.mean(xc) - grand_mean) ** 2

	if ss_total <= 0:
		return np.nan
	return float(ss_between / ss_total)


def discriminative_feature_metrics(
	features: np.ndarray,
	scores: np.ndarray,
	feature_names: Sequence[str],
	random_state: int = 42,
) -> List[Dict[str, float]]:
	y = np.asarray(scores)
	classes = np.unique(y)
	mi = np.zeros(features.shape[1], dtype=float)
	std_per_feature = np.nanstd(features, axis=0)
	variable_mask = std_per_feature > NEAR_CONSTANT_STD
	if np.any(variable_mask):
		mi_var = mutual_info_classif(
			features[:, variable_mask],
			y,
			discrete_features=False,
			random_state=random_state,
		)
		mi[variable_mask] = mi_var

	rows: List[Dict[str, float]] = []
	for i, fname in enumerate(feature_names):
		x = features[:, i]
		is_constant = bool(np.nanmax(x) - np.nanmin(x) <= NEAR_CONSTANT_STD)
		grouped = [x[y == c] for c in classes if np.sum(y == c) > 1]

		if len(grouped) >= 2 and not is_constant:
			try:
				with warnings.catch_warnings():
					warnings.simplefilter("ignore")
					f_stat, anova_p = f_oneway(*grouped)
			except Exception:
				f_stat, anova_p = np.nan, np.nan

			try:
				with warnings.catch_warnings():
					warnings.simplefilter("ignore")
					k_stat, kruskal_p = kruskal(*grouped)
			except Exception:
				k_stat, kruskal_p = np.nan, np.nan
		else:
			f_stat, anova_p, k_stat, kruskal_p = np.nan, np.nan, np.nan, np.nan

		fisher = _fisher_score_per_feature(x, y, classes)
		eta2 = _eta_squared(x, y, classes)

		rows.append(
			{
				"feature": fname,
				"mutual_info": float(mi[i]),
				"fisher_score": fisher,
				"eta_squared": eta2,
				"is_constant": int(is_constant),
				"anova_f": float(f_stat) if np.isfinite(f_stat) else np.nan,
				"anova_p": float(anova_p) if np.isfinite(anova_p) else np.nan,
				"kruskal_h": float(k_stat) if np.isfinite(k_stat) else np.nan,
				"kruskal_p": float(kruskal_p) if np.isfinite(kruskal_p) else np.nan,
			}
		)

	return rows


def _minmax(x: np.ndarray) -> np.ndarray:
	x = np.asarray(x, dtype=float)
	xmin = np.nanmin(x)
	xmax = np.nanmax(x)
	if not np.isfinite(xmin) or not np.isfinite(xmax) or np.isclose(xmin, xmax):
		return np.zeros_like(x)
	return (x - xmin) / (xmax - xmin)


def rank_features(metric_rows: List[Dict[str, float]]) -> List[Dict[str, float]]:
	mi = np.array([row["mutual_info"] for row in metric_rows], dtype=float)
	fisher = np.array([row["fisher_score"] for row in metric_rows], dtype=float)
	eta2 = np.array([row["eta_squared"] for row in metric_rows], dtype=float)
	kruskal_p = np.array([row["kruskal_p"] for row in metric_rows], dtype=float)

	with np.errstate(divide="ignore"):
		neg_log_kruskal_p = -np.log10(np.clip(kruskal_p, 1e-300, 1.0))

	score = (
		0.35 * _minmax(mi)
		+ 0.30 * _minmax(fisher)
		+ 0.25 * _minmax(eta2)
		+ 0.10 * _minmax(neg_log_kruskal_p)
	)

	ranked = []
	order = np.argsort(-score)
	for rank_idx, idx in enumerate(order, start=1):
		row = dict(metric_rows[idx])
		row["selection_score"] = float(score[idx])
		row["rank"] = rank_idx
		ranked.append(row)
	return ranked


def stage_specificity_metrics(
	features: np.ndarray,
	scores: np.ndarray,
	feature_names: Sequence[str],
) -> List[Dict[str, float]]:
	"""Compute stage-specificity metrics per feature.

	For each feature, estimate how specifically it separates one stage
	from all other stages using one-vs-rest standardized effect sizes.
	"""
	y = np.asarray(scores, dtype=int)
	classes = np.unique(y)
	rows: List[Dict[str, float]] = []

	for i, fname in enumerate(feature_names):
		x = np.asarray(features[:, i], dtype=float)
		valid = np.isfinite(x)
		x = x[valid]
		yv = y[valid]

		if x.size == 0:
			rows.append(
				{
					"feature": fname,
					"most_specific_stage": -1,
					"most_specific_stage_name": "Unknown",
					"max_one_vs_rest_effect": np.nan,
					"effect_margin": np.nan,
					"stage_mean_concentration": np.nan,
				}
			)
			continue

		effects = []
		stage_means = []
		global_mean = float(np.mean(x))

		for c in classes:
			xc = x[yv == c]
			xr = x[yv != c]
			if xc.size == 0 or xr.size == 0:
				effects.append(np.nan)
				stage_means.append(np.nan)
				continue

			mu_c = float(np.mean(xc))
			mu_r = float(np.mean(xr))
			var_c = float(np.var(xc, ddof=1)) if xc.size > 1 else 0.0
			var_r = float(np.var(xr, ddof=1)) if xr.size > 1 else 0.0
			pooled_sd = float(np.sqrt((var_c + var_r) / 2.0))
			effect = abs(mu_c - mu_r) / (pooled_sd + 1e-12)
			effects.append(effect)
			stage_means.append(mu_c)

		effects_arr = np.asarray(effects, dtype=float)
		stage_means_arr = np.asarray(stage_means, dtype=float)

		if np.any(np.isfinite(effects_arr)):
			best_idx = int(np.nanargmax(effects_arr))
			max_effect = float(effects_arr[best_idx])
			sorted_effects = np.sort(effects_arr[np.isfinite(effects_arr)])
			second_best = float(sorted_effects[-2]) if sorted_effects.size >= 2 else 0.0
			effect_margin = float(max_effect - second_best)
			best_stage = int(classes[best_idx])
		else:
			max_effect = np.nan
			effect_margin = np.nan
			best_stage = -1

		# Concentration: how much one stage mean dominates the feature profile.
		if np.any(np.isfinite(stage_means_arr)):
			dev = np.abs(stage_means_arr - global_mean)
			dev = np.where(np.isfinite(dev), dev, 0.0)
			if np.sum(dev) <= 0:
				concentration = 0.0
			else:
				p = dev / np.sum(dev)
				k = max(2, p.size)
				entropy = -np.sum(p * np.log(np.clip(p, 1e-12, 1.0)))
				concentration = float(1.0 - entropy / np.log(k))
		else:
			concentration = np.nan

		rows.append(
			{
				"feature": fname,
				"most_specific_stage": best_stage,
				"most_specific_stage_name": STAGE_NAMES.get(best_stage, f"Stage_{best_stage}"),
				"max_one_vs_rest_effect": max_effect,
				"effect_margin": effect_margin,
				"stage_mean_concentration": concentration,
			}
		)

	return rows


def rank_features_by_stage_specificity(
	stage_rows: List[Dict[str, float]],
) -> List[Dict[str, float]]:
	"""Rank features by stage specificity.

	Weighted score emphasizes strong one-vs-rest effect and uniqueness
	of that effect to a single stage.
	"""
	max_effect = np.array([row["max_one_vs_rest_effect"] for row in stage_rows], dtype=float)
	margin = np.array([row["effect_margin"] for row in stage_rows], dtype=float)
	concentration = np.array([row["stage_mean_concentration"] for row in stage_rows], dtype=float)

	# Replace NaN with 0 before min-max scaling to keep ranking stable.
	max_effect = np.where(np.isfinite(max_effect), max_effect, 0.0)
	margin = np.where(np.isfinite(margin), margin, 0.0)
	concentration = np.where(np.isfinite(concentration), concentration, 0.0)

	stage_specificity_score = (
		0.50 * _minmax(max_effect)
		+ 0.30 * _minmax(margin)
		+ 0.20 * _minmax(concentration)
	)

	ranked = []
	order = np.argsort(-stage_specificity_score)
	for rank_idx, idx in enumerate(order, start=1):
		row = dict(stage_rows[idx])
		row["stage_specificity_score"] = float(stage_specificity_score[idx])
		row["rank"] = rank_idx
		ranked.append(row)
	return ranked


def _interval_metrics(interval_mask: np.ndarray, stage_mask: np.ndarray) -> tuple[float, float, float, float]:
	"""Return (coverage, precision, lift, distinctiveness_index)."""
	stage_total = int(np.sum(stage_mask))
	inside_total = int(np.sum(interval_mask))
	inside_stage = int(np.sum(interval_mask & stage_mask))
	n_total = max(1, len(stage_mask))

	coverage = inside_stage / stage_total if stage_total > 0 else 0.0
	precision = inside_stage / inside_total if inside_total > 0 else 0.0
	base_rate = stage_total / n_total
	lift = precision / (base_rate + 1e-12)
	distinctiveness = coverage * max(0.0, lift - 1.0)
	return float(coverage), float(precision), float(lift), float(distinctiveness)


def stage_distinctive_feature_intervals(
	features: np.ndarray,
	scores: np.ndarray,
	feature_names: Sequence[str],
	interval_q_low: float = 0.20,
	interval_q_high: float = 0.80,
) -> List[Dict[str, float]]:
	"""Find stage-indicative value intervals for each single feature.

	For each stage-feature pair, the stage interval is estimated by the
	[interval_q_low, interval_q_high] quantiles of that feature within the stage.
	"""
	rows: List[Dict[str, float]] = []
	unique_stages = sorted(int(s) for s in np.unique(scores))

	for stage in unique_stages:
		stage_mask = np.asarray(scores == stage)
		for i, fname in enumerate(feature_names):
			x = np.asarray(features[:, i], dtype=float)
			finite = np.isfinite(x)
			valid_stage = stage_mask & finite
			if np.sum(valid_stage) < 5:
				continue

			stage_vals = x[valid_stage]
			lo = float(np.quantile(stage_vals, interval_q_low))
			hi = float(np.quantile(stage_vals, interval_q_high))
			if not np.isfinite(lo) or not np.isfinite(hi):
				continue

			interval_mask = finite & (x >= lo) & (x <= hi)
			coverage, precision, lift, distinctiveness = _interval_metrics(interval_mask, stage_mask)

			rows.append(
				{
					"stage": int(stage),
					"stage_name": STAGE_NAMES.get(int(stage), f"Stage_{int(stage)}"),
					"feature": str(fname),
					"interval_low": lo,
					"interval_high": hi,
					"coverage": coverage,
					"precision": precision,
					"lift": lift,
					"distinctiveness_index": distinctiveness,
				}
			)

	rows.sort(key=lambda r: (r["stage"], -r["distinctiveness_index"], -r["precision"]))
	for stage in unique_stages:
		stage_rows = [r for r in rows if r["stage"] == stage]
		for rank_idx, row in enumerate(stage_rows, start=1):
			row["rank_within_stage"] = rank_idx

	return rows


def stage_distinctive_feature_combinations(
	features: np.ndarray,
	scores: np.ndarray,
	feature_names: Sequence[str],
	top_features_per_stage: List[Dict[str, float]],
	interval_q_low: float = 0.20,
	interval_q_high: float = 0.80,
	max_pairs_per_stage: int = 12,
) -> List[Dict[str, float]]:
	"""Find stage-indicative two-feature interval combinations.

	Pairs are built from top single-feature candidates per stage and scored by
	how pure and stage-focused the joint interval box is.
	"""
	rows: List[Dict[str, float]] = []
	unique_stages = sorted(int(s) for s in np.unique(scores))
	name_to_idx = {str(n): i for i, n in enumerate(feature_names)}

	for stage in unique_stages:
		stage_mask = np.asarray(scores == stage)
		stage_candidates = [r for r in top_features_per_stage if r["stage"] == stage][:max_pairs_per_stage]
		candidate_names = [r["feature"] for r in stage_candidates if r["feature"] in name_to_idx]
		if len(candidate_names) < 2:
			continue

		for a in range(len(candidate_names)):
			for b in range(a + 1, len(candidate_names)):
				f1 = candidate_names[a]
				f2 = candidate_names[b]
				i1 = name_to_idx[f1]
				i2 = name_to_idx[f2]

				x1 = np.asarray(features[:, i1], dtype=float)
				x2 = np.asarray(features[:, i2], dtype=float)
				finite = np.isfinite(x1) & np.isfinite(x2)
				valid_stage = stage_mask & finite
				if np.sum(valid_stage) < 5:
					continue

				s1 = x1[valid_stage]
				s2 = x2[valid_stage]
				f1_lo = float(np.quantile(s1, interval_q_low))
				f1_hi = float(np.quantile(s1, interval_q_high))
				f2_lo = float(np.quantile(s2, interval_q_low))
				f2_hi = float(np.quantile(s2, interval_q_high))

				joint_mask = (
					finite
					& (x1 >= f1_lo) & (x1 <= f1_hi)
					& (x2 >= f2_lo) & (x2 <= f2_hi)
				)
				coverage, precision, lift, distinctiveness = _interval_metrics(joint_mask, stage_mask)

				rows.append(
					{
						"stage": int(stage),
						"stage_name": STAGE_NAMES.get(int(stage), f"Stage_{int(stage)}"),
						"feature_1": f1,
						"feature_1_low": f1_lo,
						"feature_1_high": f1_hi,
						"feature_2": f2,
						"feature_2_low": f2_lo,
						"feature_2_high": f2_hi,
						"coverage": coverage,
						"precision": precision,
						"lift": lift,
						"distinctiveness_index": distinctiveness,
					}
				)

	rows.sort(key=lambda r: (r["stage"], -r["distinctiveness_index"], -r["precision"]))
	for stage in unique_stages:
		stage_rows = [r for r in rows if r["stage"] == stage]
		for rank_idx, row in enumerate(stage_rows, start=1):
			row["rank_within_stage"] = rank_idx

	return rows


def _add_stage_normalized_distinctiveness(
	rows: List[Dict[str, float]],
	source_key: str = "distinctiveness_index",
	target_key: str = "distinctiveness_index_norm_stage",
) -> List[Dict[str, float]]:
	"""Add per-stage min-max normalization (0-1) for a distinctiveness metric."""
	if not rows:
		return []

	out_rows = [dict(r) for r in rows]
	stages = sorted({int(r["stage"]) for r in out_rows})

	for stage in stages:
		stage_vals = [float(r.get(source_key, np.nan)) for r in out_rows if int(r["stage"]) == stage]
		stage_vals = [v for v in stage_vals if np.isfinite(v)]
		if not stage_vals:
			for r in out_rows:
				if int(r["stage"]) == stage:
					r[target_key] = 0.0
			continue

		vmax = max(stage_vals)
		if not np.isfinite(vmax) or vmax <= 0:
			for r in out_rows:
				if int(r["stage"]) == stage:
					r[target_key] = 0.0
			continue

		for r in out_rows:
			if int(r["stage"]) != stage:
				continue
			v = float(r.get(source_key, np.nan))
			r[target_key] = float(v / vmax) if np.isfinite(v) else 0.0

	return out_rows


